"""Builds the directory's astrologer list from the real astrologers in the backend seed.

The directory used to be generated from a hand-written list that repeated the same people three times ("(2)", "(3)")
and showed prices, ratings and availability that the backend did not know about. It is now generated from
packages/database/seed_astrologers.py, so every astrologer listed here exists in the backend, can be consulted, and shows
the same name, photo, rating and AI / human status everywhere.

Run after changing the seed:  python scripts/generate_astrologers_data.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from packages.database.seed_astrologers import DEFAULT_ASTROLOGERS  # noqa: E402

PORTRAITS = ROOT / 'website/frontend/assets/portraits'
OUT = ROOT / 'website/frontend/src/pages/DirectoryPage/astrologersData.js'

# Astrologers shown in the directory, in display order, with the gender the "Help me choose" filter uses.
# Every astrologer in the backend seed is listed; append a slug here when a new one is added to the seed.
DIRECTORY = [
    ('pt-rameshwar-dwivedi', 'male'), ('vidushi-meera-devi', 'female'), ('acharya-kn-rao', 'male'),
    ('acharya-vaibhav-nath', 'male'), ('dr-meenakshi-sharma', 'female'), ('acharya-vishwanath', 'male'),
    ('pt-harinarayan-mishra', 'male'), ('vidushi-sunita-sharma', 'female'), ('dr-arvind-mohan', 'male'),
    ('vidushi-tarot-aradhana', 'female'), ('acharya-shastri', 'male'), ('dr-radhika-nair', 'female'),
    ('pt-devavrata', 'male'), ('vidushi-gayatri-bhatt', 'female'), ('acharya-raghavendra', 'male'),
    ('vidushi-priyanka-sen', 'female'), ('pt-brijesh-pandey', 'male'), ('vidushi-shambhavi', 'female'),
    ('pt-devesh-jha', 'male'), ('vidushi-shalini-kapoor', 'female'), ('acharya-mukund', 'male'),
    ('dr-krishna-murthy', 'male'), ('vidushi-kalpana-trivedi', 'female'), ('pt-govind-shastri', 'male'),
    ('vidushi-ananya-joshi', 'female'), ('pt-vidyadhar', 'male'), ('vidushi-pallavi-deshmukh', 'female'),
    ('pt-anand-swaroop', 'male'),
    # the rest of the astrologers in the backend
    ('jyotishi-kavita-devi', 'female'), ('acharya-anand-joshi', 'male'), ('dr-meenakshi-iyer', 'female'),
    ('pandit-ji-maharaj', 'male'), ('jyotishi-devendra', 'male'), ('acharya-hariprasad', 'male'),
    ('acharya-somnath', 'male'), ('pt-tribhuvan', 'male'), ('pt-janardan-shastri', 'male'),
    ('acharya-samudrika-ramesh', 'male'), ('acharya-venkatesh-dikshitar', 'male'),
]

STATUS = {'online': 'Online', 'busy': 'Busy right now', 'offline': 'Offline'}


def entry(seed, gender):
    avatar = '/' + seed['avatar'].lstrip('/')
    stem = avatar.rsplit('.', 1)[0]
    svg = stem + '.svg'
    fallback = svg if (PORTRAITS / (Path(svg).name)).exists() and 'default-avatar' not in svg else '/assets/portraits/default-avatar.svg'
    availability = seed.get('availability') or 'online'
    return {
        'id': seed['slug'],
        'slug': seed['slug'],
        'name': seed['name'],
        'name_hi': seed.get('name_hi'),
        'title': seed['title'],
        'title_hi': seed.get('title_hi'),
        'avatar': avatar,
        'fallbackAvatar': fallback,
        'rating': round(float(seed['rating']), 2),
        'review_count': seed['review_count'],
        'experience_years': seed['experience_years'],
        'price_per_minute': seed['price_per_minute'],
        'is_ai': bool(seed['is_ai']),
        'languages': seed['languages'],
        'specialties': seed['specialties'],
        'availability': availability,
        'statusLabel': STATUS.get(availability, 'Offline'),
        'gender': gender,
        'bio': seed.get('bio'),
        'bio_hi': seed.get('bio_hi'),
    }


def main():
    by_slug = {a['slug']: a for a in DEFAULT_ASTROLOGERS}
    missing = [s for s, _ in DIRECTORY if s not in by_slug]
    if missing:
        raise SystemExit(f'Not in the backend seed: {missing}')
    rows = [entry(by_slug[s], g) for s, g in DIRECTORY]
    OUT.write_text(
        f"// Generated by scripts/generate_astrologers_data.py from packages/database/seed_astrologers.py. Do not edit by hand.\n"
        f"// Every astrologer here exists in the backend, so consultation, profile and directory always agree.\n"
        f"export const ALL_ASTROLOGERS = {json.dumps(rows, ensure_ascii=False, indent=2)};\n",
        encoding='utf-8',
    )
    ai = sum(1 for r in rows if r['is_ai'])
    print(f'Wrote {len(rows)} astrologers ({ai} AI, {len(rows) - ai} human) to {OUT}')


if __name__ == '__main__':
    main()
