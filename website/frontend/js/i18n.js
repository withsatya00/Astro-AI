// RTL Languages list (Urdu, Sindhi, Kashmiri)
const RTL_LANGUAGES = ['ur', 'sd', 'ks'];

const I18n = {
  currentLang: "en",

  init() {
    if (this.initialized) return;
    this.initialized = true;
    this.sourceText = new WeakMap();
    this.sourceAttributes = new WeakMap();
    this.buildPhraseIndex();
    // Delegation also covers language selectors mounted after startup.
    document.addEventListener('change', event => {
      if (['chat-lang-select', 'global-lang-select', 'mobile-drawer-lang-select'].includes(event.target.id)) {
        this.setLanguage(event.target.value, true);
      }
    });
    this.observer = new MutationObserver(() => this.scheduleTranslations());
    this.observe();
    const saved = localStorage.getItem('astro_preferred_lang') || 'en';
    this.setLanguage(saved, false);
  },

  observe() {
    this.observer?.observe(document.body, {
      childList: true, subtree: true, characterData: true,
      attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label']
    });
  },

  scheduleTranslations() {
    if (this.translationScheduled) return;
    this.translationScheduled = true;
    queueMicrotask(() => {
      this.translationScheduled = false;
      this.applyTranslations();
    });
  },

  buildPhraseIndex() {
    this.phrases = new Map();
    this.dynamicPhrases = [];
    const normalize = value => value.replace(/\s+/g, ' ').trim();
    Object.entries(window.ASTRO_UI_LOCALES?.phrases || {}).forEach(([source, translations]) => {
      for (const value of [source, translations.en, translations.hi]) {
        if (value) this.phrases.set(normalize(value), translations);
      }
    });
    // Exact matches cover static copy; phrases cover labels with computed values.
    const escape = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    for (const [source, translations] of this.phrases) {
      if (!/__ARG\d+__/.test(source)) continue;
      if ((source.replace(/__ARG\d+__/g, '').match(/\p{L}/gu) || []).length < 3) continue;
      const slots = [];
      const pattern = source.split(/(__ARG\d+__)/).map(part => {
        if (/^__ARG\d+__$/.test(part)) { slots.push(part); return '(.+?)'; }
        return escape(part);
      }).join('');
      this.dynamicPhrases.push({ pattern: new RegExp('^' + pattern + '$', 'u'), slots, translations });
    }
    this.dynamicPhrases.sort((a, b) => b.pattern.source.length - a.pattern.source.length);
    const fragments = [...this.phrases.keys()].filter(value => value.length > 2 && !/[<>\n]|__ARG\d+__/.test(value));
    fragments.sort((a, b) => b.length - a.length);
    this.phrasePattern = fragments.length ? new RegExp(fragments.map(escape).join('|'), 'gu') : null;
  },

  text(value) {
    if (typeof value !== 'string' || !['en', 'hi'].includes(this.currentLang)) return value;
    const normalized = value.replace(/\s+/g, ' ').trim();
    const entry = this.phrases?.get(normalized);
    if (entry) return value.replace(normalized === value ? value : /\S[\s\S]*\S|\S/, entry[this.currentLang]);
    for (const phrase of this.dynamicPhrases || []) {
      const match = phrase.pattern.exec(normalized);
      if (!match) continue;
      const slots = Object.fromEntries(phrase.slots.map((slot, i) => [slot, match[i + 1]]));
      return phrase.translations[this.currentLang].replace(/__ARG\d+__/g, slot => {
        const argument = slots[slot];
        return this.phrases.get(argument)?.[this.currentLang] || argument;
      });
    }
    if (!this.phrasePattern) return value;
    // CRUCIAL SAFEGUARD: Do not fragment-replace inside Devanagari text when currentLang is English
    if (this.currentLang === 'en' && /[\u0900-\u097F]/.test(value)) {
      return value;
    }
    return value.replace(this.phrasePattern, (match, offset, source) => {
      // Do not translate parts of identifiers, words, or email addresses.
      const word = /[\p{L}\p{M}\p{N}_@]/u;
      if ((word.test(match[0]) && offset && word.test(source[offset - 1])) ||
          (word.test(match[match.length - 1]) && word.test(source[offset + match.length] || ' '))) return match;
      return this.phrases.get(match)?.[this.currentLang] || match;
    });
  },

  t(key) {
    const complete = window.ASTRO_UI_LOCALES?.keyed?.[this.currentLang];
    if (complete && complete[key] !== undefined) return complete[key];
    const dict = ASTRO_I18N[this.currentLang] || ASTRO_I18N.en;
    if (dict && dict[key] !== undefined) {
      return dict[key];
    }
    // Fallback: Hindi -> English -> raw key
    if (this.currentLang !== 'en' && ASTRO_I18N.hi && ASTRO_I18N.hi[key] !== undefined) {
      return ASTRO_I18N.hi[key];
    }
    if (ASTRO_I18N.en && ASTRO_I18N.en[key] !== undefined) {
      return ASTRO_I18N.en[key];
    }
    return key;
  },

  term(termKey) {
    const termObj = ASTRO_TERMINOLOGY[termKey];
    if (!termObj) return termKey;
    return this.text(termObj[this.currentLang] || termObj.en || termKey);
  },

  setLanguage(lang, showToast = true) {
    const previousLanguage = this.currentLang;
    if (!ASTRO_I18N[lang]) {
      lang = "en";
    }
    this.currentLang = lang;
    localStorage.setItem("astro_preferred_lang", lang);
    document.documentElement.setAttribute("lang", lang);

    // RTL Support for Urdu, Sindhi, Kashmiri
    const isRtl = RTL_LANGUAGES.includes(lang) || (ASTRO_I18N[lang] && ASTRO_I18N[lang].is_rtl);
    if (isRtl) {
      document.documentElement.setAttribute("dir", "rtl");
      document.body.classList.add("rtl-mode");
    } else {
      document.documentElement.setAttribute("dir", "ltr");
      document.body.classList.remove("rtl-mode");
    }

    // Synchronize all language dropdowns
    const chatSelect = document.getElementById("chat-lang-select");
    if (chatSelect && chatSelect.value !== lang) {
      chatSelect.value = lang;
    }

    const globalSelect = document.getElementById("global-lang-select");
    if (globalSelect && globalSelect.value !== lang) {
      globalSelect.value = lang;
    }

    const mobileDrawerSelect = document.getElementById("mobile-drawer-lang-select");
    if (mobileDrawerSelect && mobileDrawerSelect.value !== lang) {
      mobileDrawerSelect.value = lang;
    }

    // Synchronize ChatController language
    if (window.ChatController) {
      window.ChatController.currentLanguage = lang;
    }

    // Apply translations across all marked DOM elements
    this.applyTranslations();
    document.dispatchEvent(new CustomEvent('astro:languagechange', { detail: { language: lang } }));
    window.dispatchEvent(new CustomEvent('astro:languagechange', { detail: { language: lang } }));
    if (previousLanguage !== lang && window.CallingAgentService?.isCalling) {
      CallingAgentService.updateMicButton();
    }

    // Re-render dynamic widgets on language change
    if (window.App) {
      if (typeof App.loadHomePanchangBar === 'function') App.loadHomePanchangBar();
      if (typeof App.fetchAndRenderHoroscope === 'function') App.fetchAndRenderHoroscope();
    }

    if (showToast && window.App && typeof window.App.showToast === "function") {
      const msg = this.t("lang_switched");
      window.App.showToast(msg, "info");
    }
  },

  applyTranslations() {
    if (!this.sourceText) return;
    this.markedTranslations ||= new WeakMap();
    this.observer?.disconnect();
    const dict = ASTRO_I18N[this.currentLang] || ASTRO_I18N.en;

    // 1. Text elements
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const marker = `${this.currentLang}:${key}`;
      if (this.markedTranslations.get(el) === marker) return;
      this.markedTranslations.set(el, marker);
      const val = this.t(key);
      if (val && val !== key) {
        if (val.includes('<') && val.includes('>')) {
          el.innerHTML = val;
        } else if (el.children.length === 0) {
          if (el.textContent !== val) el.textContent = val;
        } else {
          const innerSpan = el.querySelector('span:not([class*="icon"]):not([class*="glyph"])') || el.lastElementChild;
          if (innerSpan && innerSpan.tagName === 'SPAN') {
            if (innerSpan.textContent !== val) innerSpan.textContent = val;
          } else {
            el.innerHTML = val;
          }
        }
      }
    });

    // 2. Placeholder elements
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const key = el.getAttribute("data-i18n-placeholder");
      const val = this.t(key);
      if (val && val !== key) {
        el.setAttribute("placeholder", val);
      }
    });

    // 3. Title / tooltip elements
    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const key = el.getAttribute("data-i18n-title");
      const val = this.t(key);
      if (val && val !== key) {
        el.setAttribute("title", val);
      }
    });

    // 4. Update page document title
    const brandName = this.t("brand_title") || "Astro Jyotish";
    const subTitle = this.t("brand_subtitle") || "Vedic Astrology";
    document.title = `${brandName} - ${subTitle}`;
    // Translate asynchronously rendered templates and dynamic labels as well.
    // Preserve source strings so switching repeatedly never translates a translation.
    const skip = 'script, style, code, pre, textarea, [translate="no"], [data-no-translate], .mandir-seva-container, .astro-mall-container, #chadawa-modal-root, .nav-dropdown-menu, [data-user-content], .user-bubble, .assistant-bubble .msg-text-content, #active-streaming-text, #call-user-transcript, #call-pandit-transcript';
    // Some HTML parsers split character entities into separate text nodes.
    // Translate a leaf's complete label before traversing individual nodes.
    document.querySelectorAll('body *').forEach(el => {
      if (el.childElementCount || el.childNodes.length < 2 || el.closest(skip)) return;
      const output = this.text(el.textContent);
      if (output !== el.textContent) el.textContent = output;
    });
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      if (!node.textContent.trim() || node.parentElement?.closest(skip)) continue;
      const previous = this.sourceText.get(node);
      const source = previous && node.textContent === previous.output ? previous.source : node.textContent;
      const output = this.text(source);
      this.sourceText.set(node, { source, output });
      if (node.textContent !== output) node.textContent = output;
    }
    document.querySelectorAll('[placeholder], [title], [aria-label]').forEach(el => {
      if (el.closest('[translate="no"], [data-user-content]')) return;
      const previous = this.sourceAttributes.get(el) || {};
      for (const attr of ['placeholder', 'title', 'aria-label']) {
        if (!el.hasAttribute(attr)) continue;
        const value = el.getAttribute(attr);
        const source = previous[attr] && previous[attr].output === value ? previous[attr].source : value;
        const output = this.text(source);
        previous[attr] = { source, output };
        if (value !== output) el.setAttribute(attr, output);
      }
      this.sourceAttributes.set(el, previous);
    });
    ['chat-lang-select', 'global-lang-select', 'mobile-drawer-lang-select'].forEach(id => {
      const select = document.getElementById(id);
      if (select) select.value = this.currentLang;
    });
    this.observe();
  }
};

window.I18n = I18n;
window.ASTRO_I18N = ASTRO_I18N;
window.ASTRO_TERMINOLOGY = ASTRO_TERMINOLOGY;
