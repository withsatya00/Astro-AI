export function getChadhavaEvent(slug) {
  if (!slug || slug === 'chadhava' || slug === 'dhanteras' || slug === 'dhanteras-lakshmi-dhanvantari-kuber') {
    return DHANTERAS_CHADHAVA_EVENT;
  }
  if (TEMPLE_CHADHAVA_REGISTRY[slug]) {
    return TEMPLE_CHADHAVA_REGISTRY[slug];
  }

  // Fallback dynamic adapter with all 18 authentic offerings
  const formatted = slug.split('-').map((s) => s.charAt(0).toUpperCase() + s.slice(1)).join(' ');
  return {
    ...DHANTERAS_CHADHAVA_EVENT,
    id: slug,
    slug: slug,
    title: `Pavitra Mandir Chadhava Seva - Shri ${formatted}`,
    breadcrumb: `Sri Mandir Chadhava Seva > Shri ${formatted}`,
    temple_location: `Shri ${formatted} Mandir, Holy Dham`,
    banner_image: `/assets/img/temples/${slug}.jpg`,
  };
}
