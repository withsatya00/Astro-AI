const TABLE = new Map(ENTRIES.map(([k, en, hi]) => [k, { en, hi }]));

/** Looks up a string in the visitor's language and fills `{name}` placeholders. Unknown keys return the key. */
export function px(key, vars) {
  const row = TABLE.get(key);
  let text = row ? (row[currentLang()] || row.en) : key;
  if (vars) Object.keys(vars).forEach(k => { text = text.split(`{${k}}`).join(vars[k]); });
  return text;
}

/** Panchang names arrive as "Tritiya (तृतीया)"; show the Hindi part in Hindi, the Latin part otherwise. */
export function bilingual(text) {
  const m = /^(.*?)\s*\((.+)\)\s*$/.exec(String(text || ''));
  if (!m) return String(text || '');
  return currentLang() === 'hi' && /[ऀ-ॿ]/.test(m[2]) ? m[2] : m[1];
}

