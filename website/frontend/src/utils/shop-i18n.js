export function translateError(message) {
  if (currentLang() !== 'hi' || typeof message !== 'string') return message;
  for (const [pattern, hindi] of ERRORS_HI) {
    const m = message.match(pattern);
    if (m) return hindi.replace(/\$(\d)/g, (_, i) => m[+i] || '');
  }
  return message;
}
