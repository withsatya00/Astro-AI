const DICT = { en: {}, hi: {} };
[...ENTRIES, ...EXTRA].forEach(([key, en, hi]) => { DICT.en[key] = en; DICT.hi[key] = hi; });

export const currentLang = () => (window.I18n && window.I18n.currentLang === 'hi' ? 'hi' : 'en');

/** Text for `key` in the site's current language, with `{name}` placeholders filled from `vars`. */
export function t(key, vars) {
  let text = DICT[currentLang()][key] ?? DICT.en[key] ?? key;
  if (vars) Object.keys(vars).forEach(k => { text = text.split(`{${k}}`).join(vars[k]); });
  return text;
}

/** Fills every [data-i18n], [data-i18n-html], [data-i18n-ph] and [data-i18n-aria] element inside `root`. */
export function applyI18n(root) {
  if (!root) return;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.getAttribute('data-i18n')); });
  root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.getAttribute('data-i18n-html')); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.getAttribute('data-i18n-ph')); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))); });
  root.querySelectorAll('[data-i18n-alt]').forEach(el => { el.setAttribute('alt', t(el.getAttribute('data-i18n-alt'))); });
}

